import { DialogueItem } from '../types';

export function extractDialoguesFromRpy(content: string): {
  dialogues: DialogueItem[];
  characters: string[];
} {
  const lines = content.split('\n');
  const dialogues: DialogueItem[] = [];
  const characterSet = new Set<string>();

  // Regular expression to match say lines:
  // e.g.:
  //   s "Hello, player!"
  //   "Narrator text here."
  //   player_name "What is this place?"
  //   e happy "With emotion tag"
  const sayRegex = /^(\s*)(?:([a-zA-Z_][a-zA-Z0-9_]*)(?:\s+[a-zA-Z0-9_]+)?)?\s*"((?:[^"\\]|\\.)*)"(\s*.*)$/;

  lines.forEach((line, index) => {
    // Skip comments
    const trimmed = line.trim();
    if (trimmed.startsWith('#')) return;

    // Skip menu choices (they end with ':')
    if (trimmed.endsWith(':')) return;

    // Check if it matches a dialogue line
    const match = line.match(sayRegex);
    if (match) {
      const char = match[2] ? match[2].trim() : 'Narrator';
      const text = match[3];

      // Exclude keywords like scene, show, image, etc. if false matched
      if (['scene', 'show', 'hide', 'default', 'define', 'jump', 'call', 'play', 'stop', 'queue', 'voice', 'return'].includes(char)) {
        return;
      }

      characterSet.add(char);

      // Extract text tags like {b}, {color=...}, [name]
      const tags: string[] = [];
      const curlyMatches = text.match(/\{[^}]+\}/g);
      if (curlyMatches) tags.push(...curlyMatches);
      const varMatches = text.match(/\[[^\]]+\]/g);
      if (varMatches) tags.push(...varMatches);

      dialogues.push({
        id: `dialogue-${index + 1}`,
        lineIndex: index + 1,
        character: char,
        originalText: text,
        translatedText: '',
        tags,
      });
    }
  });

  return {
    dialogues,
    characters: Array.from(characterSet),
  };
}

export function generateTranslationFile(
  originalFileName: string,
  dialogues: DialogueItem[],
  languageCode: string = 'thai'
): string {
  const baseName = originalFileName.replace(/\.rpy$/, '');
  const lines: string[] = [];

  lines.push(`# Translation file for ${originalFileName}`);
  lines.push(`# Language: ${languageCode}`);
  lines.push(`# Generated by Ren'Py & APK Code Studio`);
  lines.push('');

  dialogues.forEach((d) => {
    if (!d.translatedText) return;

    lines.push(`# game/${originalFileName}:${d.lineIndex}`);
    lines.push(`translate ${languageCode} ${baseName}_line_${d.lineIndex}:`);
    if (d.character && d.character !== 'Narrator') {
      lines.push(`    ${d.character} "${d.translatedText}"`);
    } else {
      lines.push(`    "${d.translatedText}"`);
    }
    lines.push('');
  });

  return lines.join('\n');
}

export function applyTranslationsToScript(
  originalCode: string,
  dialogues: DialogueItem[]
): string {
  const lines = originalCode.split('\n');
  const dialogueMap = new Map<number, string>();

  dialogues.forEach((d) => {
    if (d.translatedText) {
      dialogueMap.set(d.lineIndex - 1, d.translatedText);
    }
  });

  return lines
    .map((line, idx) => {
      const translated = dialogueMap.get(idx);
      if (!translated) return line;

      // Replace the inner quotes with translated text
      return line.replace(/"((?:[^"\\]|\\.)*)"/, `"${translated}"`);
    })
    .join('\n');
}
